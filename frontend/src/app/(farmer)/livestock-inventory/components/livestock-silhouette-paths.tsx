"use client";


export type LivestockSpeciesKey = "cattle" | "swine" | "goat" | "sheep" | "carabao" | "horse" | "poultry" | "default";

export function resolveSpeciesKey(speciesName?: string | null): LivestockSpeciesKey {
  const norm = (speciesName || "").toLowerCase();
  if (norm.includes("carabao") || norm.includes("buffalo")) return "carabao";
  if (norm.includes("cattle") || norm.includes("cow") || norm.includes("baka") || norm.includes("bovine") || norm.includes("bull") || norm.includes("heifer") || norm.includes("calf")) {
    return "cattle";
  }
  if (norm.includes("swine") || norm.includes("pig") || norm.includes("baboy") || norm.includes("hog") || norm.includes("pork")) {
    return "swine";
  }
  if (norm.includes("goat") || norm.includes("kambing") || norm.includes("caprine")) {
    return "goat";
  }
  if (norm.includes("sheep") || norm.includes("tupa") || norm.includes("ovine") || norm.includes("lamb")) {
    return "sheep";
  }
  if (norm.includes("horse") || norm.includes("kabayo")) return "horse";
  if (norm.includes("poultry") || norm.includes("chicken") || norm.includes("manok") || norm.includes("duck")) return "poultry";
  return "default";
}

